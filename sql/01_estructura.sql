SELECT current_database() AS base_actual;

DO $$
BEGIN
    IF current_database() IN ('postgres', 'template0', 'template1') THEN
        RAISE EXCEPTION 'Seleccione una base de proyecto vacia, no una base del sistema.';
    END IF;

    IF EXISTS (
        SELECT 1
        FROM pg_class c
        JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = 'monitoreo_sismologico'
          AND c.relkind IN ('r', 'p', 'v', 'm', 'f', 'S')
    ) THEN
        RAISE EXCEPTION 'El esquema ya contiene objetos. No se modifico ningun dato.';
    END IF;
END;
$$;

\echo '=== ESTRUCTURA: CREACION DE TABLAS Y RESTRICCIONES ==='
BEGIN;
CREATE SCHEMA IF NOT EXISTS monitoreo_sismologico;
SET LOCAL search_path TO monitoreo_sismologico, public;

-- Tablas
CREATE TABLE estacion_sismica (
    id_estacion INTEGER GENERATED BY DEFAULT AS IDENTITY,
    codigo VARCHAR(50) NOT NULL,
    nombre VARCHAR(150) NOT NULL,
    latitud NUMERIC NOT NULL,
    longitud NUMERIC NOT NULL,
    altitud NUMERIC,
    departamento VARCHAR(100),
    provincia VARCHAR(100),
    distrito VARCHAR(100),
    fecha_instalacion DATE,
    estado VARCHAR(40) NOT NULL
);

CREATE TABLE sensor (
    id_sensor INTEGER GENERATED BY DEFAULT AS IDENTITY,
    numero_serie VARCHAR(80) NOT NULL,
    tipo VARCHAR(80) NOT NULL,
    modelo VARCHAR(100),
    unidad_medida VARCHAR(40) NOT NULL,
    frecuencia_muestreo NUMERIC NOT NULL,
    fecha_instalacion DATE NOT NULL,
    fecha_ultimo_mantenimiento DATE,
    estado VARCHAR(40) NOT NULL,
    id_estacion INTEGER NOT NULL
);

CREATE TABLE lectura_onda (
    id_lectura BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_sensor INTEGER NOT NULL,
    fecha_hora TIMESTAMP NOT NULL,
    canal VARCHAR(40) NOT NULL,
    valor NUMERIC NOT NULL,
    es_valida BOOLEAN NOT NULL
);

CREATE TABLE evento_sismico (
    id_evento INTEGER GENERATED BY DEFAULT AS IDENTITY,
    fecha_hora_origen TIMESTAMP NOT NULL,
    latitud_epicentro NUMERIC NOT NULL,
    longitud_epicentro NUMERIC NOT NULL,
    profundidad_km NUMERIC NOT NULL,
    magnitud NUMERIC NOT NULL,
    tipo_magnitud VARCHAR(30),
    intensidad_maxima VARCHAR(40),
    referencia_geografica VARCHAR(250),
    estado_revision VARCHAR(40) NOT NULL
);

CREATE TABLE deteccion (
    id_sensor INTEGER NOT NULL,
    id_evento INTEGER NOT NULL,
    hora_deteccion TIMESTAMP NOT NULL,
    aceleracion_maxima NUMERIC,
    calidad VARCHAR(40)
);

CREATE TABLE alerta (
    id_alerta INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_evento INTEGER NOT NULL,
    fecha_hora_emision TIMESTAMP NOT NULL,
    nivel VARCHAR(40) NOT NULL,
    mensaje TEXT NOT NULL,
    magnitud_estimada NUMERIC,
    estado VARCHAR(40) NOT NULL
);

-- Claves primarias
ALTER TABLE estacion_sismica
    ADD CONSTRAINT pk_estacion_sismica PRIMARY KEY (id_estacion);

ALTER TABLE sensor
    ADD CONSTRAINT pk_sensor PRIMARY KEY (id_sensor);

ALTER TABLE lectura_onda
    ADD CONSTRAINT pk_lectura_onda PRIMARY KEY (id_lectura);

ALTER TABLE evento_sismico
    ADD CONSTRAINT pk_evento_sismico PRIMARY KEY (id_evento);

ALTER TABLE deteccion
    ADD CONSTRAINT pk_deteccion PRIMARY KEY (id_sensor, id_evento);

ALTER TABLE alerta
    ADD CONSTRAINT pk_alerta PRIMARY KEY (id_alerta);

-- Claves foraneas
ALTER TABLE sensor
    ADD CONSTRAINT fk_sensor_estacion
    FOREIGN KEY (id_estacion) REFERENCES estacion_sismica(id_estacion);

ALTER TABLE lectura_onda
    ADD CONSTRAINT fk_lectura_sensor
    FOREIGN KEY (id_sensor) REFERENCES sensor(id_sensor);

ALTER TABLE deteccion
    ADD CONSTRAINT fk_deteccion_sensor
    FOREIGN KEY (id_sensor) REFERENCES sensor(id_sensor),
    ADD CONSTRAINT fk_deteccion_evento
    FOREIGN KEY (id_evento) REFERENCES evento_sismico(id_evento);

ALTER TABLE alerta
    ADD CONSTRAINT fk_alerta_evento
    FOREIGN KEY (id_evento) REFERENCES evento_sismico(id_evento);

-- Restricciones de unicidad
ALTER TABLE estacion_sismica
    ADD CONSTRAINT uq_estacion_codigo UNIQUE (codigo);

ALTER TABLE sensor
    ADD CONSTRAINT uq_sensor_numero_serie UNIQUE (numero_serie);

ALTER TABLE lectura_onda
    ADD CONSTRAINT uq_lectura_sensor_fecha_canal
    UNIQUE (id_sensor, fecha_hora, canal);

-- Restricciones de dominio
ALTER TABLE estacion_sismica
    ADD CONSTRAINT ck_estacion_latitud CHECK (latitud BETWEEN -90 AND 90),
    ADD CONSTRAINT ck_estacion_longitud CHECK (longitud BETWEEN -180 AND 180);

ALTER TABLE sensor
    ADD CONSTRAINT ck_sensor_frecuencia CHECK (frecuencia_muestreo > 0),
    ADD CONSTRAINT ck_sensor_mantenimiento
    CHECK (fecha_ultimo_mantenimiento IS NULL
           OR fecha_ultimo_mantenimiento >= fecha_instalacion);

ALTER TABLE evento_sismico
    ADD CONSTRAINT ck_evento_latitud
    CHECK (latitud_epicentro BETWEEN -90 AND 90),
    ADD CONSTRAINT ck_evento_longitud
    CHECK (longitud_epicentro BETWEEN -180 AND 180),
    ADD CONSTRAINT ck_evento_profundidad CHECK (profundidad_km >= 0);

ALTER TABLE deteccion
    ADD CONSTRAINT ck_deteccion_aceleracion
    CHECK (aceleracion_maxima IS NULL OR aceleracion_maxima >= 0);

COMMIT;

\echo '=== ESTRUCTURA: COMPROBACION ==='
SELECT table_name AS tabla
FROM information_schema.tables
WHERE table_schema = 'monitoreo_sismologico'
  AND table_type = 'BASE TABLE'
ORDER BY table_name;

SELECT CASE contype
           WHEN 'p' THEN 'PRIMARY KEY'
           WHEN 'f' THEN 'FOREIGN KEY'
           WHEN 'u' THEN 'UNIQUE'
           WHEN 'c' THEN 'CHECK'
           WHEN 'n' THEN 'NOT NULL'
       END AS restriccion, COUNT(*) AS cantidad
FROM pg_constraint
WHERE connamespace = 'monitoreo_sismologico'::regnamespace
GROUP BY contype
ORDER BY restriccion;

DO $$
BEGIN
    IF (SELECT COUNT(*) FROM information_schema.tables
        WHERE table_schema = 'monitoreo_sismologico'
          AND table_type = 'BASE TABLE') <> 6 THEN
        RAISE EXCEPTION 'No se encontraron las seis tablas esperadas.';
    END IF;

    IF (SELECT COUNT(*) FROM pg_constraint
        WHERE connamespace = 'monitoreo_sismologico'::regnamespace
          AND contype = 'p') <> 6
       OR (SELECT COUNT(*) FROM pg_constraint
        WHERE connamespace = 'monitoreo_sismologico'::regnamespace
          AND contype = 'f') <> 5
       OR (SELECT COUNT(*) FROM pg_constraint
        WHERE connamespace = 'monitoreo_sismologico'::regnamespace
          AND contype = 'u') <> 3
       OR (SELECT COUNT(*) FROM pg_constraint
        WHERE connamespace = 'monitoreo_sismologico'::regnamespace
          AND contype = 'c') <> 8 THEN
        RAISE EXCEPTION 'Las restricciones no coinciden con el modelo.';
    END IF;

    RAISE NOTICE 'OK: seis tablas y restricciones comprobadas.';
END;
$$;

